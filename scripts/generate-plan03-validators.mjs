import { readFile, readdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import Ajv2020 from 'ajv/dist/2020.js'
import { _ } from 'ajv/dist/compile/codegen/index.js'
import standaloneCode from 'ajv/dist/standalone/index.js'
import addFormats from 'ajv-formats'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const directory = resolve(root, 'src/contracts/generated/enterprise-security-v1/runtime-schemas')
const output = resolve(root, 'src/enterprise-security/plan03-validators.generated.ts')

function numericFormats(value) {
  if (Array.isArray(value)) return value.map(numericFormats)
  if (value === null || typeof value !== 'object') return value
  const next = Object.fromEntries(Object.entries(value).map(([key, item]) => [key, numericFormats(item)]))
  const maximum = { uint8: 255, uint16: 65_535, uint32: 4_294_967_295 }[next.format]
  if (maximum !== undefined) {
    delete next.format
    next.type ??= 'number'
    next.minimum = Math.max(next.minimum ?? 0, 0)
    next.maximum = Math.min(next.maximum ?? maximum, maximum)
    next.multipleOf = 1
  }
  return next
}

const ajv = new Ajv2020({
  strict: false,
  allErrors: false,
  code: { source: true, esm: true },
})
addFormats(ajv)
ajv.addKeyword({
  keyword: 'x-maxUtf8Bytes',
  type: 'string',
  schemaType: 'number',
  code(context) {
    const { data, schemaCode } = context
    context.fail(_`new TextEncoder().encode(${data}).byteLength > ${schemaCode}`)
  },
})
// This one format needs Rust-equivalent URL normalization checks in the decoder.
// The generated schema still enforces its structural pattern here.
ajv.addFormat('provider-https-url', true)
const exports = {}
const requestEntries = []
const responseEntries = []
let errorEntry
for (const file of (await readdir(directory)).sort()) {
  // Shared structural schemas are consumed by their owning specialised
  // validators; they are not Plan 03 request/response operations.
  if (file === 'conditional-source-evidence.schema.json' || file === 'scim-entry.schema.json') continue
  const side =
    file === 'error.schema.json'
      ? 'error'
      : file.endsWith('.request.schema.json')
        ? 'request'
        : file.endsWith('.response.schema.json')
          ? 'response'
          : null
  const suffix = side === 'request' ? '.request.schema.json' : '.response.schema.json'
  const key = side === 'error' ? 'error' : side === null ? null : file.slice(0, -suffix.length)
  if (key === null || !/^[a-z0-9._]+$/u.test(key)) throw new Error(`Unexpected Plan 03 schema: ${file}`)
  const schema = numericFormats(JSON.parse(await readFile(resolve(directory, file), 'utf8')))
  delete schema.$id
  const id = `plan03:${side}:${key}`
  ajv.addSchema(schema, id)
  const exportName = `plan03_${side}_${key.replaceAll('.', '_')}`
  exports[exportName] = id
  if (side === 'request') requestEntries.push([key, exportName])
  else if (side === 'response') responseEntries.push([key, exportName])
  else errorEntry = exportName
}
if (requestEntries.length !== 42 || responseEntries.length !== 42 || errorEntry === undefined) {
  throw new Error(
    `Expected 42 Plan 03 requests, 42 responses and one error; got ${requestEntries.length}/${responseEntries.length}/${errorEntry === undefined ? 0 : 1}`,
  )
}

let source = standaloneCode(ajv, exports)
source = source
  .replace('"use strict";', '')
  .replaceAll('require("ajv/dist/runtime/ucs2length").default', 'ucs2length')
  .replaceAll('require("ajv/dist/runtime/equal").default', 'deepEqual')
  .replaceAll('require("ajv-formats/dist/formats").fullFormats', 'fullFormats')

const imports = []
if (source.includes('ucs2length')) {
  imports.push("import ucs2Module from 'ajv/dist/runtime/ucs2length.js'")
  imports.push('const ucs2length = ucs2Module.default ?? ucs2Module')
}
if (source.includes('deepEqual')) {
  imports.push("import equalModule from 'ajv/dist/runtime/equal.js'")
  imports.push('const deepEqual = equalModule.default ?? equalModule')
}
if (source.includes('fullFormats')) {
  imports.push("import formatModule from 'ajv-formats/dist/formats.js'")
  imports.push('const { fullFormats } = formatModule')
}
if (/require\(/u.test(source)) throw new Error('Unsupported CommonJS helper in Plan 03 validators')
const generated = [
  '/* Generated by scripts/generate-plan03-validators.mjs. Do not edit. */',
  '// @ts-nocheck',
  ...imports,
  '',
  source.trim(),
  '',
  'export const plan03RequestValidators = {',
  ...requestEntries.map(([key, exportName]) => `  ${JSON.stringify(key)}: ${exportName},`),
  '} as const',
  '',
  'export const plan03ResponseValidators = {',
  ...responseEntries.map(([key, exportName]) => `  ${JSON.stringify(key)}: ${exportName},`),
  `  error: ${errorEntry},`,
  '} as const',
  '',
].join('\n')

if (process.argv.includes('--check')) {
  const existing = await readFile(output, 'utf8').catch(() => '')
  if (existing !== generated) throw new Error('Plan 03 runtime validators are stale')
} else {
  await writeFile(output, generated)
}
