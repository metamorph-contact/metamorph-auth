import { readFile, writeFile } from 'node:fs/promises'
import { dirname, isAbsolute, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { admitTheme } from '@polymorph/theme/admit'

const uiRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const release = JSON.parse(await readFile(resolve(uiRoot, 'catalog/identity-ui-release.development.json'), 'utf8'))
const blocks = []
for (const pairing of release.themePairings ?? []) {
  const system = await controlledJson(pairing.systemSpecPath)
  const palette = await controlledJson(pairing.paletteSpecPath)
  const admission = admitTheme({ system, palette })
  if (!admission.lawful || admission.system?.name !== pairing.systemId || admission.palette?.name !== pairing.paletteId) {
    throw new Error(`Polymorph rejected ${pairing.themePairingId}`)
  }
  blocks.push(`/* ${pairing.themePairingId}; generated by scripts/generate-theme-css.mjs */\n${admission.css}`)
}
await writeFile(resolve(uiRoot, 'src/presentation/generated-themes.css'), `${blocks.join('\n')}\n`, 'utf8')

async function controlledJson(path) {
  if (typeof path !== 'string' || isAbsolute(path)) throw new Error('Theme path must be relative')
  const candidate = resolve(uiRoot, path)
  const fromRoot = relative(uiRoot, candidate)
  if (fromRoot.startsWith('..') || isAbsolute(fromRoot)) throw new Error('Theme path escapes the UI root')
  return JSON.parse(await readFile(candidate, 'utf8'))
}
